#!/usr/bin/env node
/**
 * manifold — the engine of Topos. (AGPL: the invariant is shared.)
 *
 *   manifold validate schools/lotus.yaml   → does the manifest hold the contract?
 *   manifold render schools/lotus.yaml     → demo/<school>/index.html from the manifest
 *   manifold serve schools/lotus.yaml      → render + http://localhost:4173
 *
 * v0 scope on purpose: the validator implements the subset of JSON Schema
 * draft-07 that spec/manifest.schema.json actually uses (required, type,
 * const, enum, minimum, minItems, properties, items). If the schema ever
 * needs more, the validator grows with it — or we adopt ajv and say so.
 */
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { createServer } from "node:http";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import YAML from "yaml";

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = join(HERE, "..");
const SCHEMA = JSON.parse(readFileSync(join(ROOT, "spec", "manifest.schema.json"), "utf8"));

/* ---------------- tiny honest JSON Schema validator (subset) ------------- */
function validate(value, schema, path = "$", errors = []) {
  if (schema.const !== undefined && JSON.stringify(value) !== JSON.stringify(schema.const))
    errors.push(`${path}: expected const ${JSON.stringify(schema.const)}`);
  if (schema.enum && !schema.enum.includes(value))
    errors.push(`${path}: must be one of ${schema.enum.join(", ")}`);
  if (schema.type === "object") {
    if (value === null || typeof value !== "object" || Array.isArray(value)) { errors.push(`${path}: must be an object`); return errors; }
    for (const req of schema.required ?? [])
      if (!(req in value)) errors.push(`${path}.${req}: required and missing`);
    for (const [k, sub] of Object.entries(schema.properties ?? {}))
      if (k in value) validate(value[k], sub, `${path}.${k}`, errors);
  } else if (schema.type === "array") {
    if (!Array.isArray(value)) { errors.push(`${path}: must be an array`); return errors; }
    if (schema.minItems && value.length < schema.minItems) errors.push(`${path}: needs at least ${schema.minItems} items`);
    if (schema.items) value.forEach((v, i) => validate(v, schema.items, `${path}[${i}]`, errors));
  } else if (schema.type === "string") {
    if (typeof value !== "string") errors.push(`${path}: must be a string`);
  } else if (schema.type === "number") {
    if (typeof value !== "number") errors.push(`${path}: must be a number`);
    else if (schema.minimum !== undefined && value < schema.minimum) errors.push(`${path}: must be >= ${schema.minimum}`);
  } else if (schema.type === "boolean") {
    if (typeof value !== "boolean") errors.push(`${path}: must be a boolean`);
  }
  return errors;
}

/* ---------------- extra contract beyond the schema ----------------------- */
function contract(manifest) {
  const problems = [];
  const seen = new Set();
  for (const p of manifest.programs) {
    if (seen.has(p.code)) problems.push(`programs: duplicate code ${p.code}`);
    seen.add(p.code);
    if (p.price.published && p.price.amount <= 0)
      problems.push(`program ${p.code}: published price must be a real amount (no invented figures)`);
  }
  for (const f of manifest.communication.funnels)
    if (!/^[^@\s]+@[^@\s]+\.[a-z]{2,}$/i.test(f.address))
      problems.push(`funnel ${f.key}: address is not an address (it must be a real, proven mailbox)`);
  return problems;
}

/* ---------------- render: the manifest IS the site ----------------------- */
function render(m) {
  const c = m.brand.palette;
  const programs = m.programs.map((p) => `
    <article class="card">
      <h3>${p.name}</h3>
      <p class="meta">${p.place} · ages ${p.ages} · ${p.season.starts} → ${p.season.ends}</p>
      ${p.price.published ? `<p class="price">${p.price.currency === "THB" ? "฿" : ""}${p.price.amount.toLocaleString()} / ${p.price.unit}${p.price.earlyBird ? ` <span class="eb">Early Bird until ${p.price.deadline}</span>` : ""}</p>` : ""}
      <a class="door" href="${p.door}">Enrol →</a>
    </article>`).join("");
  const funnels = m.communication.funnels.map((f) => `<a href="mailto:${f.address}">${f.address}</a> <span>· ${f.purpose}</span>`).join("<br>");
  return `<!doctype html>
<html lang="${m.identity.defaultLocale}">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>${m.identity.name} — generated by manifold</title>
<style>
  :root { --brand:${c.brand}; --deep:${c.brandDeep}; --sun:${c.sun}; --teal:${c.teal}; --ink:${c.ink}; --paper:${c.paper}; --shell:${c.shell}; }
  * { box-sizing: border-box; }
  body { margin:0; font-family: ${m.brand.fonts.display}, system-ui, sans-serif; color: var(--ink); background: var(--paper); }
  header { background: var(--deep); color: white; padding: 48px 24px; text-align:center; }
  header h1 { margin:0; font-size: clamp(1.6rem, 4vw, 3rem); }
  header .tag { color: var(--sun); font-weight: 700; margin-top: 8px; }
  header .alt { opacity:.75; font-size:.9rem; margin-top:4px; }
  main { max-width: 960px; margin: 0 auto; padding: 32px 20px; }
  h2 { color: var(--brand); }
  .grid { display:grid; gap:16px; grid-template-columns: repeat(auto-fit, minmax(260px, 1fr)); }
  .card { background: var(--shell); border-radius: 20px; padding: 20px; box-shadow: 0 6px 20px rgb(47 29 58 / 0.10); }
  .card h3 { margin:0 0 6px; color: var(--deep); }
  .meta { font-size:.85rem; color: var(--brand); margin:0 0 8px; }
  .price { font-weight:700; }
  .eb { color: var(--teal); font-size:.8rem; font-weight:600; }
  .door { display:inline-block; background: var(--sun); color: var(--deep); padding:8px 16px; border-radius:999px; text-decoration:none; font-weight:700; }
  footer { background: var(--deep); color: white; padding: 32px 24px; font-size:.9rem; }
  footer a { color: var(--sun); }
  .stamp { text-align:center; opacity:.6; font-size:.75rem; padding:12px; }
</style>
</head>
<body>
  <header>
    <h1>${m.identity.name}</h1>
    <div class="tag">${m.identity.tagline ?? ""}</div>
    ${m.identity.altName ? `<div class="alt">also known as ${m.identity.altName}</div>` : ""}
  </header>
  <main>
    <h2>Our ${m.topology.entity}s</h2>
    <div class="grid">${programs}</div>
  </main>
  <footer>
    <strong>${m.identity.name}</strong> · ${m.identity.domain}<br>
    ${m.communication.postalAddress} · <a href="tel:${m.communication.phone}">${m.communication.phone}</a><br>
    ${funnels}
  </footer>
  <div class="stamp">this page was generated from ${"schools/"}.yaml by manifold — the manifest IS the site</div>
</body>
</html>`;
}

/* ---------------- commands ----------------------------------------------- */
const [cmd, file] = process.argv.slice(2);
if (!cmd || !file) {
  console.log("usage: manifold <validate|render|serve> schools/<school>.yaml");
  process.exit(cmd ? 1 : 0);
}
const manifest = YAML.parse(readFileSync(file, "utf8"));
const errors = [...validate(manifest, SCHEMA), ...contract(manifest)];

if (cmd === "validate") {
  if (errors.length) { console.error(`✗ ${file}: ${errors.length} problem(s)`); errors.forEach((e) => console.error("  · " + e)); process.exit(1); }
  const plural = (w) => (/y$/.test(w) ? w.slice(0, -1) + "ies" : /s$|sh$|ch$|x$/.test(w) ? w + "es" : w + "s");
  console.log(`✓ ${file} holds the contract — ${manifest.programs.length} ${plural(manifest.topology.entity)}, ${manifest.operations.primitives.length} primitives, ${manifest.identity.locales.length} locale(s).`);
} else if (cmd === "render" || cmd === "serve") {
  if (errors.length) { console.error(`✗ refusing to render a broken manifest (${errors.length} problems)`); errors.forEach((e) => console.error("  · " + e)); process.exit(1); }
  const slug = file.split("/").pop().replace(/\.ya?ml$/, "");
  const out = join(ROOT, "demo", slug);
  mkdirSync(out, { recursive: true });
  const html = render(manifest);
  writeFileSync(join(out, "index.html"), html);
  console.log(`✓ rendered → ${join("demo", slug, "index.html")} (${(html.length / 1024).toFixed(1)} KB)`);
  if (cmd === "serve") {
    createServer((_req, res) => { res.writeHead(200, { "content-type": "text/html; charset=utf-8" }); res.end(html); })
      .listen(4173, () => console.log("→ http://localhost:4173  (Ctrl+C to stop)"));
  }
}
